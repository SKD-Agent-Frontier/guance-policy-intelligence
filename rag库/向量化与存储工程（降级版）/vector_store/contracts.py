"""存储接口与模型接口分离；业务层不依赖SQLite连接或Qdrant客户端。

将来接回服务端数据库时，实现这些操作并修改storage.open_stores即可。
source/record/payload均为带来源身份的字典；向量为4096维float32数组。
"""
from typing import Protocol, Iterable

# 两路检索共用的公开过滤契约；业务层不需要导入某个数据库的SDK。
FILTER_KEYS={'planid','area_name','area_code','period_key','document_type','source_type','representation_type','document_version_id'}


class MetadataStore(Protocol):
    def put_documents(self, records: Iterable[dict]): ...
    def put_objects(self, kind: str, records: Iterable[dict]): ...
    def register_links(self, children: Iterable[dict], relations: Iterable[dict]): ...
    def document(self, document_id: str) -> dict | None: ...
    def object(self, object_id: str) -> dict | None: ...
    def object_owners(self) -> dict[str,str | None]: ...
    def begin(self, generation: str, manifest: dict): ...
    def put_record(self, generation: str, record: dict, payload: dict, text: str | None, description=None): ...
    def commit(self): ...
    def task(self, generation: str, input_hash: str, status: str, error=None): ...
    def unfinished(self, generation: str) -> int: ...
    def members(self, generation: str) -> Iterable[dict]: ...
    def release(self, generation: str) -> dict | None: ...
    def ready(self, generation: str, validation: dict): ...
    def active(self) -> dict | None: ...
    def activate(self, generation: str, expected_revision: int) -> dict: ...
    def related(self, source_ids: list) -> list: ...
    def integrity(self) -> bool: ...
    def rebase(self, old_root: str, new_root: str): ...
    def close(self): ...


class VectorStore(Protocol):
    def create(self, collection: str): ...
    def upsert(self, collection: str, records: list): ...
    def scan(self, collection: str): ...
    def ids(self, collection: str) -> set: ...
    def count(self, collection: str) -> int: ...
    def search(self, collection: str, vector, limit: int, filters: dict) -> list: ...
    def close(self): ...


class LexicalStore(Protocol):
    def build(self, generation: str, documents: list): ...
    def load(self, generation: str): ...
    def search(self, query: str, limit: int, allowed_ids: set | None) -> list: ...
    def validate(self, generation: str, expected_documents: list[tuple[str,str]]) -> dict: ...
    def close(self): ...
